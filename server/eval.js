/* ---------- ให้คะแนน ---------- */
function rx(list, s) { return list.some(r => r.test(s)); }
function itemText(it) { return [it.title, it.topic, it.quote, it.explanation].filter(Boolean).join(' '); }
function obText(o) { return [o.what, o.quote, o.amount, o.when].filter(Boolean).join(' '); }

export function scoreCase(c, result, ob) {
  const items = Array.isArray(result?.items) ? result.items.filter(it => !it.missing) : [];
  const obs = Array.isArray(ob?.obligations) ? ob.obligations : [];
  const risk = c.risks.map(r => ({ id: r.id, hit: items.some(it => rx(r.any, itemText(it))) }));
  const obl = c.obligations.map(e => ({ id: e.id, hit: obs.some(o => rx(e.any, obText(o)) && (!e.kind || o.kind === e.kind || (e.kind === 'pay' && o.kind === 'deliver'))) }));
  const quoteOk = (result?.items || []).filter(it => !it.missing).length;
  const quoteAll = (result?.items || []).length;
  const high = items.filter(it => it.level === 'check_detail').length;
  const overAlert = typeof c.maxHigh === 'number' && high > c.maxHigh;
  return {
    id: c.id, name: c.name,
    risk: { found: risk.filter(x => x.hit).length, total: risk.length, missed: risk.filter(x => !x.hit).map(x => x.id) },
    obl: { found: obl.filter(x => x.hit).length, total: obl.length, missed: obl.filter(x => !x.hit).map(x => x.id) },
    quotes: { ok: quoteOk, total: quoteAll },
    high, overAlert,
  };
}

function pct(a, b) { return b ? Math.round((a / b) * 1000) / 10 : 100; }

/* ---------- งานรันแบบเบื้องหลัง (แอดมินกดเริ่ม แล้วหน้าเว็บถามความคืบหน้า) ---------- */
const jobs = new Map();
export function getJob(id) { return jobs.get(id) || null; }
export function lastJob() { let j = null; for (const v of jobs.values()) if (!j || v.startedAt > j.startedAt) j = v; return j; }

export function startEval({ only } = {}) {
  for (const j of jobs.values()) if (j.status === 'running') return j;
  const list = Array.isArray(only) && only.length ? CASES.filter(c => only.includes(c.id)) : CASES;
  const job = { id: crypto.randomBytes(6).toString('hex'), status: 'running', startedAt: Date.now(), done: 0, total: list.length, cases: [], errors: [], summary: null };
  jobs.set(job.id, job);
  if (jobs.size > 5) jobs.delete(jobs.keys().next().value);
  (async () => {
    let i = 0;
    const worker = async () => {
      while (i < list.length) {
        const c = list[i++];
        try {
          const [result, ob] = await Promise.all([
            analyzeContract(c.text, c.type, 'th'),
            extractObligations(c.text, 'th').catch(e => ({ error: e.message })),
          ]);
          // ตรวจว่า quote มีอยู่จริงแบบเดียวกับหน้าเว็บ (ตัดช่องว่างทั้งหมดก่อนเทียบ)
          const sq = s => String(s || '').replace(/\s+/g, '');
          const src = sq(c.text);
          (result.items || []).forEach(it => { it.missing = !(it.quote && src.includes(sq(it.quote))); });
          const sc = scoreCase(c, result, ob);
          if (ob?.error) sc.oblError = ob.error;
          job.cases.push(sc);
        } catch (e) {
          job.errors.push({ id: c.id, error: e.message });
        }
        job.done++;
      }
    };
    await Promise.all([worker(), worker(), worker()]);
    const S = (k, f) => job.cases.reduce((a, x) => a + x[k][f], 0);
    job.summary = {
      riskRecall: pct(S('risk', 'found'), S('risk', 'total')),
      oblRecall: pct(S('obl', 'found'), S('obl', 'total')),
      quoteValid: pct(S('quotes', 'ok'), S('quotes', 'total')),
      overAlerts: job.cases.filter(x => x.overAlert).length,
      failed: job.errors.length,
    };
    job.summary.overall = Math.round(((job.summary.riskRecall + job.summary.oblRecall + job.summary.quoteValid) / 3) * 10) / 10;
    job.status = 'done'; job.finishedAt = Date.now();
    job.cases.sort((a, b) => list.findIndex(c => c.id === a.id) - list.findIndex(c => c.id === b.id));
    console.log(`[eval] done ${job.id}: overall ${job.summary.overall}% risk ${job.summary.riskRecall}% obl ${job.summary.oblRecall}% quotes ${job.summary.quoteValid}%`);
  })().catch(e => { job.status = 'error'; job.errors.push({ id: '*', error: e.message }); });
  return job;
}
